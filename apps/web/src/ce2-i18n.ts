const stageKeys = {
  familiar: 'stageFamiliar',
  fluent: 'stageFluent',
  learning: 'stageLearning',
  unseen: 'stageUnseen',
} as const satisfies Record<string, Ce2TranslationKey>

export function ce2Translate(locale: Locale, key: Ce2TranslationKey, values: Values = {}): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    ce2Catalogs[locale][key],
  )
}

export const ce2Copy = (locale: Locale) => ({
  skill: (skill: Ce2Skill): string => ce2Catalogs[locale][skillKeys[skill]],
  stage: (stage: 'familiar' | 'fluent' | 'learning' | 'unseen'): string =>
    ce2Catalogs[locale][stageKeys[stage]],
  t: (key: Ce2TranslationKey, values?: Values): string => ce2Translate(locale, key, values),
})

export type { Ce2TranslationKey }
