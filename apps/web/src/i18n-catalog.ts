const translations: Readonly<Record<Locale, Readonly<Record<TranslationKey, string>>>> = {
  en: english,
  fr: french,
  'zh-Hans': simplifiedChinese,
}

export function catalogForLocale(locale: Locale): Readonly<Record<TranslationKey, string>> {
  return translations[locale]
}

export function resolveLocale(value: string | null | undefined): Locale {
  return Schema.is(LocaleSchema)(value) ? value : 'fr'
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  values: TranslationValues = {},
): string {
  return Object.entries(values).reduce(
    (copy, [name, value]) => copy.replaceAll(`{${name}}`, String(value)),
    translations[locale][key],
  )
}

export function translatePlantName(locale: Locale, plantId: GardenPlantId): string {
  return translate(locale, `plant.${plantId}`)
}
